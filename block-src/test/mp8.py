import asyncio, sys, json
sys.path.insert(0, __import__('os').path.dirname(__import__('os').path.abspath(__file__)))
from mplib import Mp, K
async def main():
    m = await Mp().start(1, w=900, h=560)
    pg = m.pg[0]
    await m.ev(0, f"() => {{ {K}.R.skip = false; localStorage.removeItem('gm_name'); }}")
    await pg.click('#bOnline'); await m.wait(400); await m.shot(0, 'ui_online_empty')
    await pg.click('#bNewOnline'); await m.wait(300)
    print('no name →', await m.ev(0, f"() => [{K}.ui.menu, document.activeElement && document.activeElement.id]"))
    await pg.fill('#inNick', 'アオ')
    await pg.click('#bLook'); await m.wait(300)
    await pg.click('#lookRows > div:nth-child(4) .btn:nth-child(3)'); await pg.click('#lookRows > div:nth-child(3) .btn:nth-child(2)'); await pg.click('#lookRows > div:nth-child(2) .btn:nth-child(3)')
    await m.wait(200); await m.shot(0, 'ui_look')
    await pg.click('#mLook [data-back]'); await m.wait(200)
    await pg.click('#bNewOnline'); await m.wait(300)
    print('mNew', await m.ev(0, f"() => [{K}.ui.menu, {K}.ui.segVal('segNet'), document.getElementById('netNote').textContent]"))
    await pg.fill('#inName', 'みんなの島'); await pg.fill('#inSeed', 'さくら')
    await pg.click('#segRules .btn:nth-child(1)')
    await m.wait(200); await m.shot(0, 'ui_new')
    await pg.click('#bStart')
    await m.playing(0); await m.wait(2500)
    code = await m.ev(0, f"() => {K}.net.code")
    print('code', code, 'rules', await m.ev(0, f"() => JSON.stringify({K}.game.rules)"), 'look', await m.ev(0, f"() => {K}.settings.look.join('')"))
    # 2人目：招待リンクで来る（なまえは前に決めてある）→ そのまま入る
    p1 = await m.add(query='room=' + code, name='ミドリ')
    await m.playing(1); await m.wait(2500)
    print('p1 joined', await m.ev(1, f"() => [{K}.net.code, [...{K}.net.peers.values()].map(p => [p.name, p.look.join('')])]"))
    await m.ev(1, f"() => {{ const p = {K}.player; p.z -= 3; p.x += 1; p.yaw = Math.PI; {K}.game.needSafeSpot = 2; }}")
    await m.ev(0, f"() => {{ const p = {K}.player; p.yaw = 0; p.pitch = -0.05; }}")
    await m.wait(1200)
    if await m.ev(0, f"() => {K}.game.state") == 'playing': await pg.keyboard.press('Escape')
    await m.wait(800)
    await m.shot(0, 'ui_pause')
    print('pause', await m.ev(0, f"() => [{K}.game.state, document.getElementById('netCode').textContent, document.getElementById('netWho').textContent, document.getElementById('bQuit').textContent]"))
    t0 = await m.ev(0, f"() => {K}.game.world.tick"); await m.wait(1500); t1 = await m.ev(0, f"() => {K}.game.world.tick")
    print('world keeps running while paused:', t1 - t0, 'ticks')
    await pg.click('#bRules'); await m.wait(300); await pg.click('#segRules2 .btn:nth-child(5)'); await m.wait(800); await m.shot(0, 'ui_rules')
    print('rules p1 after change', await m.ev(1, f"() => JSON.stringify({K}.game.rules)"))
    await pg.click('#mRules [data-back]'); await m.wait(200); await pg.click('#bInvite'); await m.wait(500)
    print('invite', await m.ev(0, f"() => [{K}.ui.inviteUrl(), {K}.ui.menu, document.getElementById('msgText').textContent.slice(0, 60)]"))
    # 3人目：なまえなしで招待リンク → 入力画面
    p2 = await m.add(query='room=' + code)
    await m.ev(2, f"() => {{ {K}.R.skip = false; }}")
    await m.wait(600)
    print('p2 screen', await m.ev(2, f"() => [{K}.ui.menu, document.getElementById('inCode').value, {K}.net.getName()]"))
    print('errs', [e for e in m.errs() if '404' not in e][:8])
    await m.close()
asyncio.run(main())
